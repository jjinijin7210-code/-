// 생성에 참고자료로 쓰기 위함 (2026-07-19 요청 - "미국에서는 지금 어떤 형식이 인기인가?"
// "일본에서는 어떤 썸네일 스타일이 많이 쓰이나?" 같은 비교).
// ============================================================

export function buildMarketAnalysisMessages({ videosByRegion }) {
  const system = `너는 여러 나라의 SNS/유튜브 트렌드를 비교 분석하는 마케팅 리서처야.
아래 각 나라의 인기 영상 제목 목록을 보고, 실제로 관찰되는 경향만 근거로 간결하게 분석해줘.
확실하지 않은 건 추측해서 지어내지 말고 "명확한 경향은 안 보임"이라고 써.
반드시 한국어로, 아래 형식의 순수 텍스트로만 답해 (JSON 아님, 마크다운 헤더(#) 쓰지 마):

[미국]
- 지금 인기 있는 형식/소재:
- 특징:

[일본]
- 지금 인기 있는 형식/소재:
- 특징:

[차이점]
-`

  const userText = Object.entries(videosByRegion)
    .map(
      ([region, videos]) =>
        `${region} 인기 영상 제목:\n${videos.map((v) => `- ${v.title} (채널: ${v.channelTitle})`).join('\n')}`
    )
    .join('\n\n')

  return {
    system,
    messages: [{ role: 'user', content: userText }],
  }
}
